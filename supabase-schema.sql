create table if not exists public.games (
  id bigint generated by default as identity primary key,
  game_id text not null unique,
  installation_id text not null,
  human_name text not null default 'Lastivka',
  human_color text not null check (human_color in ('w','b')),
  opponent_elo integer not null,
  estimated_elo integer,
  placement_game boolean not null default false,
  status text not null default 'active' check (status in ('active','complete')),
  result text,
  result_label text,
  final_fen text,
  pgn text,
  san_moves jsonb not null default '[]'::jsonb,
  uci_moves jsonb not null default '[]'::jsonb,
  started_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz
);

create index if not exists games_installation_started_idx
  on public.games (installation_id, started_at desc);

alter table public.games enable row level security;

